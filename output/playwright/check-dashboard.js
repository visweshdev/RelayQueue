async page => {
 const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 const tabs=page.context().pages().length;
 await page.goto('http://localhost:8000/');
 await page.setViewportSize({width:1440,height:1000});
 await page.getByLabel('Access key',{exact:true}).fill('invalid-key');
 await page.getByRole('button',{name:'Connect',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Access key not accepted'}).waitFor();
 await page.getByRole('button',{name:'Try local demo',exact:true}).click();
 await page.getByText('Workspace connected',{exact:true}).waitFor();
 await page.locator('#rows tr').first().waitFor();
 await page.getByRole('button',{name:'Load older jobs',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('#rows tr').length>12);
 const count=await page.locator('#rows tr').count();
 await page.waitForTimeout(5600);
 if(await page.locator('#rows tr').count()!==count)throw Error('Polling discarded pagination');
 await page.getByLabel('Search loaded jobs').fill('no-job-matches-this');
 await page.getByText('No matching jobs',{exact:true}).waitFor();
 await page.getByLabel('Search loaded jobs').fill('');
 await page.getByRole('button',{name:'Refresh',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('#rows tr').length===12);
 await page.locator('.job-link').first().click();
 await page.getByRole('dialog').waitFor();
 await page.locator('#job-title').filter({hasNotText:'Loading job'}).waitFor();
 await page.keyboard.press('Escape');
 if(await page.getByRole('dialog').isVisible())throw Error('Escape did not close details');
 await page.screenshot({path:'output/playwright/dashboard.png',fullPage:true});
 await page.locator('nav a[href="#upload"]').click();
 await page.getByRole('button',{name:'Create report',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Choose a CSV file'}).waitFor();
 await page.getByRole('button',{name:'Use sample data',exact:true}).click();
 await page.getByText('Sample sales.csv selected',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Create report',exact:true}).click();
 await page.locator('#result-summary').filter({hasText:'50.10'}).waitFor();
 await page.screenshot({path:'output/playwright/dashboard-result.png'});
 await page.getByRole('button',{name:'Done',exact:true}).click();
 await page.locator('nav a[href="#guide"]').click();
 await page.getByText('Built to work with your code.',{exact:true}).waitFor();
 if(page.context().pages().length!==tabs)throw Error('Navigation opened a new tab');
 await page.getByRole('link',{name:'Open interactive API reference in this tab'}).click();
 await page.waitForURL('**/docs');
 if(page.context().pages().length!==tabs)throw Error('Docs opened a new tab');
 await page.goBack();
 await page.getByRole('button',{name:'Try local demo',exact:true}).click();
 await page.getByText('Workspace connected',{exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 await page.locator('nav a[href="#upload"]').click();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.screenshot({path:'output/playwright/dashboard-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Disconnect',exact:true}).click();
 if(await page.getByRole('button',{name:'Create report',exact:true}).isEnabled())throw Error('Upload enabled after disconnect');
 if(errors.length)throw Error(errors.join('; '));
 console.log('PASS: invalid key, connect, pagination preservation, search, refresh, details, Escape, upload validation, sample report, same-tab navigation, mobile, disconnect; no JavaScript errors.');
}
